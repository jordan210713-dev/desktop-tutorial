        <!-- Peces Ángel -->
        <section class="equipo">

            <h2>
                <i class="fa-solid fa-fish"></i>
                Pez Ángel o Escalar
            </h2>

            <p>
                <strong>Nombre científico:</strong>
                Pterophyllum scalare.
            </p>

            <p>
                El pez ángel, también conocido como escalar,
                es una especie de agua dulce originaria
                de Sudamérica.

                Se caracteriza por su cuerpo comprimido
                lateralmente, sus aletas largas y su
                forma triangular.

                Existen diferentes variedades de colores,
                como plateados, negros, blancos,
                marmoleados y koi.
            </p>

            <img src="img/angel.jpg"
                 alt="Pez ángel o escalar"
                 class="imagen-seccion">

            <h3>Características principales</h3>

            <ul>
                <li>Temperatura recomendada: 25 a 28 °C.</li>
                <li>pH aproximado: 6.0 a 7.5.</li>
                <li>Comportamiento generalmente tranquilo.</li>
                <li>Puede volverse territorial al reproducirse.</li>
                <li>Necesita un acuario con buena altura.</li>
                <li>Puede vivir varios años con buenos cuidados.</li>
            </ul>

            <h3>Alimentación</h3>

            <p>
                Los peces ángel son omnívoros.
                Pueden consumir alimentos comerciales
                de buena calidad, artemia, larvas
                y otros alimentos adecuados para peces
                tropicales.
            </p>

            <h3>Reproducción</h3>

            <p>
                Los escalares forman parejas reproductoras
                y suelen depositar sus huevos sobre
                superficies verticales, como hojas anchas,
                troncos o tubos.

                Ambos padres pueden participar en el
                cuidado de los huevos y las crías.
            </p>

        </section>

        <!-- Peces Disco -->
        <section class="servicios">

            <h2>
                <i class="fa-solid fa-fish-fins"></i>
                Pez Disco
            </h2>

            <p>
                <strong>Nombre científico:</strong>
                Symphysodon spp.
            </p>

            <p>
                Los peces disco son originarios de
                la cuenca amazónica y destacan por
                su cuerpo redondeado y sus colores
                llamativos.

                Son considerados peces muy atractivos,
                pero requieren mayor atención a la
                calidad del agua y a la estabilidad
                de las condiciones del acuario.
            </p>

            <img src="img/disco.jpg"
                 alt="Pez disco de agua dulce"
                 class="imagen-seccion">

            <h3>Características principales</h3>

            <ul>
                <li>Temperatura habitual: 28 a 30 °C.</li>
                <li>pH orientativo: 6.0 a 7.0.</li>
                <li>Son peces sociales que suelen mantenerse en grupos.</li>
                <li>Necesitan acuarios amplios y estables.</li>
                <li>Son sensibles a cambios bruscos del agua.</li>
                <li>Existen variedades azules, rojas y turquesas.</li>
            </ul>

            <h3>Alimentación</h3>

            <p>
                Los peces disco necesitan una dieta
                variada y de buena calidad.

                Se pueden alimentar con pellets
                especiales para discos, alimentos
                congelados adecuados y otras opciones
                nutritivas.
            </p>

            <h3>Reproducción</h3>

            <p>
                Los discos depositan sus huevos
                sobre superficies verticales.

                Una característica muy especial
                es que las crías recién nacidas,
                cuando comienzan a nadar libremente,
                se alimentan de una secreción
                nutritiva producida por la piel
                de sus padres.
            </p>

        </section>

